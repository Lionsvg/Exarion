// ===========================================================================
//  Exarion - Police bitmap 5x7
//
//  Chaque glyphe tient dans 5 colonnes de 7 pixels. Une colonne = un octet,
//  bit 0 = ligne du haut.
//
//  POURQUOI PAS UNE VRAIE POLICE : charger un .ttf demande FreeType, un
//  atlas de textures, des metriques et du kerning. Pour une console de
//  debug et des libelles de HUD, une grille de pixels suffit, ne depend de
//  rien, et se dessine avec les rectangles qu'on a deja.
//
//  Couvre l'ASCII 32 a 93. Les minuscules sont rendues en majuscules :
//  c'est l'usage classique des consoles de debug.
// ===========================================================================

