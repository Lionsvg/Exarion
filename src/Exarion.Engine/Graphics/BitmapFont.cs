        /// <summary>Colonne d'un glyphe, ou 0 si le caractere n'existe pas.</summary>
        public static byte GetColumn(char c, int column)
        {
            if (column < 0 || column >= GlyphWidth)
                return 0;

            // Minuscules ramenees en majuscules.
            if (c >= 'a' && c <= 'z')
                c = (char)(c - 'a' + 'A');

            if (c < FirstChar || c > LastChar)
                return 0;

            int index = (c - FirstChar) * GlyphWidth + column;
            return index < Glyphs.Length ? Glyphs[index] : (byte)0;
        }

        /// <summary>Largeur d'une chaine en pixels, pour une echelle donnee.</summary>
        public static float MeasureWidth(string text, float scale)
            => string.IsNullOrEmpty(text) ? 0f : (text.Length * Advance - 1) * scale;

        public static float LineHeight(float scale) => GlyphHeight * scale;
    }
